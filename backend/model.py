def make_record(turns):
    messages = []
    for i, content in enumerate(turns):
        role = "user" if i % 2 == 0 else "assistant"
        m = {"role": role, "content": content}
        if role == "assistant":
            m["name"] = NAME
        messages.append(m)
    return {"messages": messages}


def record_key(rec):
    return json.dumps(rec, ensure_ascii=False)


def add(records_list, turns):
    rec = make_record(turns)
    k = record_key(rec)
    if k in seen:
        return False
    seen.add(k)
    records_list.append(rec)
    return True


def fill(template, combo):
    if not combo:
        return template
    out = template
    for k, v in combo.items():
        out = out.replace("{" + k + "}", v)
    return out


def slot_combinations(slots):
    if not slots:
        return [{}]
    keys = list(slots.keys())
    combos = [{}]
    for k in keys:
        nc_all = []
        for c in combos:
            for v in slots[k]:
                nc = dict(c)
                nc[k] = v
                nc_all.append(nc)
        combos = nc_all
    return combos


