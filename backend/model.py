main_records = []
for theme in THEMES:
    combos = slot_combinations(theme.get("slots", {}))
    for user_t, asst_t in theme["pairs"]:
        for combo in combos:
            u = fill(user_t, combo)
            a_base = fill(asst_t, combo)
            for end in ENDINGS_LIGHT:
                add(main_records, [u, a_base.replace("{END}", end)])
            # マルチターンは1パターンのみ軽く追加
            cont_u, cont_a_tmpl = rng.choice(CONTINUATIONS)
            end2 = rng.choice(ENDINGS_LIGHT)
            add(main_records, [u, a_base.replace("{END}", ENDINGS_LIGHT[0]),
                                cont_u, cont_a_tmpl.replace("{END}", end2)])
print(f"メインテーマ(抑制版) 生成件数: {len(main_records)}")

deepdive_records = []
for u, a_base in DEEPDIVE_PAIRS:
    for end in DEEPDIVE_ENDINGS_LIGHT:
        add(deepdive_records, [u, a_base.replace("{END}", end)])
    cont_u, cont_a_tmpl = rng.choice(CONTINUATIONS)
    add(deepdive_records, [u, a_base.replace("{END}", DEEPDIVE_ENDINGS_LIGHT[0]),
                            cont_u, cont_a_tmpl.replace("{END}", ENDINGS_LIGHT[0])])
print(f"深掘り型(抑制版) 生成件数: {len(deepdive_records)}")

casual_records = []
