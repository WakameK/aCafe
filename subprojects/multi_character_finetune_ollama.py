"""## 3. キャラクターシート → システムプロンプトの自動生成

シート内の項目を、そのキャラの一人称・口調の手がかりも含めて
自然文のシステムプロンプトに変換します。項目名は日本語のままでOKです
(辞書に無い項目は自動的に無視されます)。

"""

def build_system_prompt(char: dict) -> str:
    name = char.get("名前", char["key"])
    alias = char.get("別名", "")
    first_person = alias.split("/")[-1] if alias else "私"

    lines = []
    lines.append(f"あなたは「{name}」というキャラクターです。一人称は「{first_person}」を使ってください。")
    if alias:
        lines.append(f"呼び名・別名: {alias}")

    basic_keys = ["役職", "年齢", "性別", "誕生日", "血液型", "身長", "体重"]
    basic = [f"{k}: {char[k]}" for k in basic_keys if char.get(k)]
    if basic:
        lines.append("基本情報 - " + " / ".join(basic))

    detail_keys = [
        ("性格", "性格"),
        ("個性", "個性・特性"),
        ("特技", "特技"),
        ("能力・スキル", "能力・スキル"),
        ("見た目", "見た目"),
        ("生い立ち", "生い立ち"),
        ("背景", "背景"),
        ("その他", "その他の設定"),
        ("カルテ", "カルテ(本人の傾向)"),
        ("生物心理社会モデル", "生物心理社会モデル"),
    ]
    for key, label in detail_keys:
        if char.get(key):
            lines.append(f"[{label}] {char[key]}")

    lines.append(
        "会話では上記の性格・個性・生い立ちを一貫して反映し、"
        f"他のキャラとは違う「{name}」独自の話し方・視点・知識の癖がはっきり伝わるように応答してください。"
        "設定を一度に説明的に語らず、自然な受け答えの中でにじませてください。"
    )
    return "\n".join(lines)


