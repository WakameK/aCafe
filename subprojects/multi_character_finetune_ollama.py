"""## 5. (任意) 対話データがあるキャラだけLoRA追加学習

このステップは**完全に任意**です。飛ばしても全キャラ分のモデルは出力されます。

もし特定のキャラだけ口調・語彙の癖をより強く焼き込みたい場合は、
そのキャラの`key`と同名の`.jsonl`(例: `aya.jsonl`)をアップロードしてください。
形式は1行1サンプルのマルチターン対話です:

```json
{"messages": [
  {"role": "user", "content": "..."},
  {"role": "assistant", "content": "..."}
]}
```

ファイルが無いキャラは自動でスキップされ、第4節の共有GGUFがそのまま使われます。

"""

from google.colab import files
import json

uploaded = files.upload()  # 任意: aya.jsonl など。何もアップロードせず実行してもOK(全員スキップ)

def load_dataset_jsonl(path):
    data = []
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.strip()
            if not line:
                continue
            data.append(json.loads(line))
    return data

for c in CHARACTERS:
    fname = f"{c['key']}.jsonl"
    if fname in uploaded:
        c["raw_data"] = load_dataset_jsonl(fname)
        print(f"{c['key']}: {len(c['raw_data'])}件 読み込みました → 追加学習します")
    else:
        print(f"{c['key']}: 対話データなし → 共有GGUFをそのまま使用します")

from datasets import Dataset
from trl import SFTTrainer
from transformers import TrainingArguments


def format_example(example, system_prompt, tokenizer):
    messages = [{"role": "system", "content": system_prompt}]
    for m in example["messages"]:
        messages.append({"role": m["role"], "content": m["content"]})
    text = tokenizer.apply_chat_template(
        messages, tokenize=False, add_generation_prompt=False
    )
    return {"text": text}


def train_and_export_character(char, num_train_epochs=3):
    if not char.get("raw_data"):
        return  # 第4節の共有GGUFをそのまま使う

    print(f"\n===== 「{char.get('名前', char['key'])}」({char['key']}) の追加学習を開始 =====")

    model, tokenizer = FastLanguageModel.from_pretrained(
        model_name=BASE_MODEL_NAME,
        max_seq_length=max_seq_length,
        dtype=dtype,
        load_in_4bit=load_in_4bit,
    )
    model = FastLanguageModel.get_peft_model(
        model,
        r=16,
        target_modules=[
            "q_proj", "k_proj", "v_proj", "o_proj",
            "gate_proj", "up_proj", "down_proj",
        ],
        lora_alpha=16,
        lora_dropout=0,
        bias="none",
        use_gradient_checkpointing="unsloth",
        random_state=3407,
    )

    hf_dataset = Dataset.from_list(char["raw_data"])
    hf_dataset = hf_dataset.map(
        lambda ex: format_example(ex, char["system_prompt"], tokenizer)
    )

    trainer = SFTTrainer(
        model=model,
        tokenizer=tokenizer,
        train_dataset=hf_dataset,
        dataset_text_field="text",
        max_seq_length=max_seq_length,
        dataset_num_proc=2,
        packing=False,
        args=TrainingArguments(
            per_device_train_batch_size=2,
            gradient_accumulation_steps=4,
            warmup_steps=10,
            num_train_epochs=num_train_epochs,
            learning_rate=2e-4,
            fp16=not torch.cuda.is_bf16_supported(),
            bf16=torch.cuda.is_bf16_supported(),
            logging_steps=10,
            optim="adamw_8bit",
            weight_decay=0.01,
            lr_scheduler_type="linear",
            seed=3407,
            output_dir=f"outputs_{char['key']}",
            report_to="none",
        ),
    )
    trainer.train()

    own_gguf_dir = f"ollama_package/{char['key']}"
    model.save_pretrained_gguf(
        own_gguf_dir,
        tokenizer,
        quantization_method=QUANT_METHOD,
    )
    own_gguf_files = [f for f in os.listdir(own_gguf_dir) if f.endswith(".gguf")]
    char["own_gguf_dir"] = own_gguf_dir
    char["own_gguf_filename"] = own_gguf_files[0]
    print(f"専用GGUFを作成しました: {own_gguf_dir}/{own_gguf_files[0]}")

    del model, tokenizer, trainer, hf_dataset
    gc.collect()
    torch.cuda.empty_cache()


for c in CHARACTERS:
    train_and_export_character(c)

"""## 6. キャラごとに `Modelfile` を自動生成

- 追加学習した(専用GGUFがある)キャラ → 自分のGGUFを`FROM`で参照
- 追加学習していないキャラ → 第4節の共有GGUFを相対パスで参照

どちらの場合も、フォルダの中身は「そのキャラの`Modelfile`」になるので、
`ollama create <key> -f Modelfile` すればキャラ専用モデルとして動きます。

"""

def write_modelfile(char):
    char_dir = f"ollama_package/{char['key']}"
    os.makedirs(char_dir, exist_ok=True)

    if char.get("own_gguf_filename"):
        # このキャラ専用に学習・書き出したGGUFを使う
        from_line = f"FROM ./{char['own_gguf_filename']}"
    else:
        # 共有GGUFを相対パスで参照する(重みは共通、個性はシステムプロンプトで表現)
        from_line = f"FROM ../_shared_base/{SHARED_GGUF_FILENAME}"

    modelfile_content = f'''{from_line}

TEMPLATE """{{{{ if .System }}}}<|start_header_id|>system<|end_header_id|>

{{{{ .System }}}}<|eot_id|>{{{{ end }}}}<|start_header_id|>user<|end_header_id|>

{{{{ .Prompt }}}}<|eot_id|><|start_header_id|>assistant<|end_header_id|>

"""

SYSTEM """{char["system_prompt"]}"""

PARAMETER stop "<|eot_id|>"
PARAMETER temperature 0.7
PARAMETER num_ctx 2048
'''
    path = f"{char_dir}/Modelfile"
    with open(path, "w", encoding="utf-8") as f:
        f.write(modelfile_content)
    print(f"Modelfileを作成しました: {path}")


for c in CHARACTERS:
    write_modelfile(c)

